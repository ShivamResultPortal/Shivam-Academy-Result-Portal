export function computeGrade(
  percentage: number,
  passPercentage: number = 40
): { grade: string; gradePoint: number; status: 'QUALIFIED' | 'NEEDS IMPROVEMENT' } {
  if (percentage < passPercentage) {
    return { grade: 'D (Below Cutoff)', gradePoint: 0, status: 'NEEDS IMPROVEMENT' };
  }
  if (percentage >= 90) return { grade: 'A+ (Merit)', gradePoint: 10, status: 'QUALIFIED' };
  if (percentage >= 80) return { grade: 'A (Distinction)', gradePoint: 9, status: 'QUALIFIED' };
  if (percentage >= 70) return { grade: 'B+ (First Class)', gradePoint: 8, status: 'QUALIFIED' };
  if (percentage >= 60) return { grade: 'B (High Pass)', gradePoint: 7, status: 'QUALIFIED' };
  if (percentage >= 50) return { grade: 'C+ (Pass)', gradePoint: 6, status: 'QUALIFIED' };
  return { grade: 'C (Average)', gradePoint: 5, status: 'QUALIFIED' };
}
